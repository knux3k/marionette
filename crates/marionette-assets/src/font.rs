/// The character actually drawn for `c`.
pub fn shown(c: char) -> char {
    let c = c.to_ascii_uppercase();
    if c == ' ' || GLYPHS.iter().any(|(g, _)| *g == c) {
        c
    } else {
        '?'
    }
}

/// Top-left pixel of `c`'s cell in the font atlas.
pub fn cell(c: char) -> (u32, u32) {
    let i = shown(c) as u32 - 32;
    ((i % COLS) * CELL_W, (i / COLS) * CELL_H)
}

/// The atlas: white glyphs on transparent background, 96x48 pixels.
pub fn atlas() -> crate::Image {
    let (w, h) = (COLS * CELL_W, ROWS * CELL_H);
    let mut rgba = vec![0u8; (w * h * 4) as usize];
    for (c, rows) in GLYPHS {
        let (cx, cy) = cell(*c);
        for (ry, bits) in rows.iter().enumerate() {
            for rx in 0..5u32 {
                if bits & (0b10000 >> rx) != 0 {
                    let i = (((cy + ry as u32) * w + cx + rx) * 4) as usize;
                    rgba[i..i + 4].copy_from_slice(&[255, 255, 255, 255]);
                }
            }
        }
    }
    crate::Image {
        width: w,
        height: h,
        rgba,
        srgb: true,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_glyph_has_a_distinct_cell_and_lowercase_maps_up() {
        let mut cells: Vec<(u32, u32)> = GLYPHS.iter().map(|(c, _)| cell(*c)).collect();
        cells.sort();
        cells.dedup();
        assert_eq!(cells.len(), GLYPHS.len());
        assert_eq!(cell('a'), cell('A'));
        assert_eq!(shown('~'), '?');
    }
}
