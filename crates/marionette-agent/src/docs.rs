//! Reference documents generated from code, so they cannot drift: the operation table and
//! every component/resource schema. Written by `marionette docs`; `marionette docs --check`
//! (run by a test) fails when the committed files are stale.

use crate::Agent;
use marionette_core::schema;
use serde_json::Value;
use std::fmt::Write;

/// A short type description from a JSON Schema fragment.
fn ty(s: &Value) -> String {
    if let Some(r) = s.get("$ref").and_then(Value::as_str) {
        return r.rsplit('/').next().unwrap_or(r).to_string();
    }
    if let Some(c) = s.get("const") {
        return c.to_string();
    }
    if let Some(list) = s
        .get("anyOf")
        .or_else(|| s.get("oneOf"))
        .and_then(Value::as_array)
    {
        let parts: Vec<String> = list.iter().map(ty).collect();
        return parts.join(" | ");
    }
    match s.get("type") {
        Some(Value::String(t)) if t == "array" => {
            format!("array of {}", s.get("items").map_or("any".into(), ty))
        }
        Some(Value::String(t)) if t == "object" => {
            if let Some(props) = s.get("properties").and_then(Value::as_object) {
                if props.len() == 1 && s.get("required").is_some() {
                    let (k, v) = props.iter().next().expect("one");
                    return format!("{{{k}: {}}}", ty(v));
                }
                let fields: Vec<String> = props.keys().cloned().collect();
                return format!("object {{{}}}", fields.join(", "));
            }
            "object".into()
        }
        Some(Value::String(t)) => t.clone(),
        Some(Value::Array(ts)) => ts
            .iter()
            .filter_map(Value::as_str)
            .collect::<Vec<_>>()
            .join(" | "),
        _ if s.as_bool() == Some(true) || s.as_object().is_some_and(|o| o.is_empty()) => "any".into(),
        _ => "any".into(),
    }
}

fn one_line(s: &str) -> String {
    s.split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace('|', "\\|")
}

fn fields_table(out: &mut String, schema: &Value) {
    let Some(props) = schema.get("properties").and_then(Value::as_object) else {
        out.push_str("No fields.\n\n");
        return;
    };
    let required: Vec<&str> = schema
        .get("required")
        .and_then(Value::as_array)
        .map(|r| r.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    out.push_str("| Field | Type | Required | Description |\n| --- | --- | --- | --- |\n");
    for (name, s) in props {
        let desc = s
            .get("description")
            .and_then(Value::as_str)
            .map(one_line)
            .unwrap_or_default();
        let req = if required.contains(&name.as_str()) {
            "yes"
        } else {
            ""
        };
        let _ = writeln!(out, "| `{name}` | {} | {req} | {desc} |", one_line(&ty(s)));
    }
    out.push('\n');
}

/// `docs/ai/reference/operations.md`.
pub fn operations(agent: &Agent) -> String {
    let mut out = String::from(
        "# Operations reference\n\nGENERATED by `marionette docs` from the operation table in \
         `crates/marionette-agent`. Do not edit by hand.\n\nEvery operation is available as \
         `marionette op <name> '<json>' --json` and as an MCP tool of the same name \
         (`marionette mcp`). Mutating operations are refused in read-only mode.\n\n",
    );
    out.push_str("| Operation | Mutating | Summary |\n| --- | --- | --- |\n");
    for o in agent.operations() {
        let _ = writeln!(
            out,
            "| `{}` | {} | {} |",
            o.name,
            if o.mutating { "yes" } else { "no" },
            one_line(o.description)
        );
    }
    out.push('\n');
    for o in agent.operations() {
        let _ = writeln!(
            out,
            "## `{}`\n\n{}\n\nMutating: {}.\n\nInput:\n",
            o.name,
            one_line(o.description),
            if o.mutating { "yes" } else { "no" }
        );
        fields_table(&mut out, &o.input_schema);
        out.push_str("Output:\n\n");
        fields_table(&mut out, &o.output_schema);
    }
    out
}

/// `docs/ai/reference/components.md`.
pub fn components(agent: &Agent) -> String {
    let doc = schema::schema(agent.registry());
    let mut out = String::from(
        "# Components and resources reference\n\nGENERATED by `marionette docs` from the type registry \
         (built-in types plus the input, physics and audio modules). Do not edit by hand. The full JSON \
         Schema is printed by `marionette schema`.\n\n",
    );
    let defs = doc["$defs"].as_object().cloned().unwrap_or_default();
    for kind in ["component", "resource"] {
        let _ = writeln!(
            out,
            "## {}s\n",
            if kind == "component" {
                "Component"
            } else {
                "Resource"
            }
        );
        for (name, s) in &defs {
            if s.get("x-marionette-kind").and_then(Value::as_str) != Some(kind) {
                continue;
            }
            let desc = s
                .get("description")
                .and_then(Value::as_str)
                .map(one_line)
                .unwrap_or_default();
            let rust = s.get("x-rust-type").and_then(Value::as_str).unwrap_or("");
            let _ = writeln!(out, "### `{name}`\n\n{desc}\n\nRust type: `{rust}`.\n");
            if let Some(variants) = s.get("oneOf").and_then(Value::as_array) {
                let _ = writeln!(
                    out,
                    "One of: {}\n",
                    variants.iter().map(ty).collect::<Vec<_>>().join(", ")
                );
            } else {
                fields_table(&mut out, s);
            }
        }
    }
    out
}

